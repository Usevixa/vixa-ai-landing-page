// Generates src/data/africaMap.ts from real country polygons (world.geo.json,
// Natural Earth derived). Equirectangular projection at equal x/y scale —
// Africa straddles the equator almost symmetrically, so it reads true without
// needing a fancier projection.
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = '/private/tmp/claude-501/-Users-sarmueil-Desktop-vixa-ai-page/78ed05c3-66cc-4b51-a60f-46eec59a2c7c/scratchpad/countries.geo.json';
const OUT = '/Users/sarmueil/Desktop/vixa-ai-page/src/data/africaMap.ts';

// every African country, so the landmass is complete
const AFRICA = new Set(`DZA AGO BEN BWA BFA BDI CMR CPV CAF TCD COM COG COD CIV DJI EGY GNQ ERI ETH
GAB GMB GHA GIN GNB KEN LSO LBR LBY MDG MWI MLI MRT MUS MAR MOZ NAM NER NGA RWA STP SEN SYC SLE
SOM ZAF SSD SDN SWZ TZA TGO TUN UGA ZMB ZWE ESH`.split(/\s+/).filter(Boolean));

// where VIXA is live — ISO3 -> display name
const ACTIVE = {
  NGA: 'Nigeria', KEN: 'Kenya', GHA: 'Ghana', ZAF: 'South Africa', TZA: 'Tanzania',
  UGA: 'Uganda', RWA: 'Rwanda', ETH: 'Ethiopia', SEN: 'Senegal', CIV: "Côte d'Ivoire",
  CMR: 'Cameroon', BEN: 'Benin', TGO: 'Togo', ZMB: 'Zambia', ZWE: 'Zimbabwe',
  MWI: 'Malawi', BWA: 'Botswana', EGY: 'Egypt', MAR: 'Morocco',
};

const geo = JSON.parse(readFileSync(SRC, 'utf8'));
const feats = geo.features.filter((f) => AFRICA.has(f.id));
console.log(`african features: ${feats.length}`);

const rings = (f) =>
  f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;

// --- bounds
let minLng = 180, maxLng = -180, minLat = 90, maxLat = -90;
for (const f of feats) {
  for (const poly of rings(f)) {
    for (const ring of poly) {
      for (const [lng, lat] of ring) {
        if (lng < minLng) minLng = lng;
        if (lng > maxLng) maxLng = lng;
        if (lat < minLat) minLat = lat;
        if (lat > maxLat) maxLat = lat;
      }
    }
  }
}
// drop the far-flung island territories that would blow out the frame
minLng = Math.max(minLng, -19);
maxLng = Math.min(maxLng, 52);
console.log(`bounds lng ${minLng.toFixed(1)}..${maxLng.toFixed(1)} lat ${minLat.toFixed(1)}..${maxLat.toFixed(1)}`);

const W = 1000;
const scale = W / (maxLng - minLng);
const H = Math.round((maxLat - minLat) * scale);
const px = (lng, lat) => [
  +((lng - minLng) * scale).toFixed(1),
  +((maxLat - lat) * scale).toFixed(1),
];

// --- paths, with a light douglas-peucker-ish decimation (drop points closer
// than EPS px to the previous one) to keep the bundle small
const EPS = 1.6;
const toPath = (f) => {
  let d = '';
  for (const poly of rings(f)) {
    for (const ring of poly) {
      let last = null;
      let started = false;
      for (const [lng, lat] of ring) {
        const [x, y] = px(lng, lat);
        if (last && Math.abs(x - last[0]) < EPS && Math.abs(y - last[1]) < EPS) continue;
        d += started ? `L${x} ${y}` : `M${x} ${y}`;
        started = true;
        last = [x, y];
      }
      if (started) d += 'Z';
    }
  }
  return d;
};

// --- marker position: centroid of the country's largest ring, which lands
// inside the landmass for every country in ACTIVE
const centroid = (f) => {
  let best = null, bestArea = 0;
  for (const poly of rings(f)) {
    for (const ring of poly) {
      let a = 0, cx = 0, cy = 0;
      for (let i = 0; i < ring.length - 1; i++) {
        const [x1, y1] = px(...ring[i]);
        const [x2, y2] = px(...ring[i + 1]);
        const cross = x1 * y2 - x2 * y1;
        a += cross;
        cx += (x1 + x2) * cross;
        cy += (y1 + y2) * cross;
      }
      a *= 0.5;
      if (Math.abs(a) > Math.abs(bestArea)) {
        bestArea = a;
        best = [+(cx / (6 * a)).toFixed(1), +(cy / (6 * a)).toFixed(1)];
      }
    }
  }
  return best;
};

const paths = feats.map((f) => ({ id: f.id, d: toPath(f) })).filter((p) => p.d);
const markers = Object.entries(ACTIVE).map(([id, name]) => {
  const f = feats.find((x) => x.id === id);
  if (!f) throw new Error(`missing feature for ${id}`);
  const [x, y] = centroid(f);
  return { id, name, x, y };
});

const out = `// GENERATED by scripts/build-africa-map.mjs — do not edit by hand.
// Real country polygons (world.geo.json), equirectangular, equal x/y scale.
export const MAP_W = ${W};
export const MAP_H = ${H};

/** Every African country outline, for the landmass. */
export const COUNTRY_PATHS: ReadonlyArray<{ id: string; d: string }> = ${JSON.stringify(paths)};

/** Countries where VIXA is live, positioned at each country's centroid. */
export const ACTIVE_MARKERS: ReadonlyArray<{ id: string; name: string; x: number; y: number }> = ${JSON.stringify(markers, null, 0)};
`;
writeFileSync(OUT, out);

const kb = (out.length / 1024).toFixed(0);
console.log(`viewBox 0 0 ${W} ${H} | ${paths.length} paths | ${markers.length} markers | ${kb}KB`);
console.log('marker sample:', markers.slice(0, 4).map((m) => `${m.id}(${m.x},${m.y})`).join(' '));
